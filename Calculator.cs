namespace MyApp
{
    public class Calculator
    {
        public int Add(int a, int b)
        {
            return a + b;
        }       
        public int Subtract(int a, int b)
        {
            return a - b;
        }
         public int Multiplie(int a, int b)
        {
            return a * b;
        }
        public double Divide(double a, double b)
        {
            return a / b;
        }
    }
}